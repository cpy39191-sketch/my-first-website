const categoryView =
  document.getElementById("categoryView");

const locationView =
  document.getElementById("locationView");

const locationGrid =
  document.getElementById("locationGrid");

const locationTitle =
  document.getElementById("locationTitle");

const locationEyebrow =
  document.getElementById("locationEyebrow");

const locationDescription =
  document.getElementById("locationDescription");

const backButton =
  document.getElementById("backButton");


/* =====================================
   CATEGORY CARDS
===================================== */

const categoryCards =
  document.querySelectorAll(".category-card");


categoryCards.forEach(card => {

  card.addEventListener("click", () => {

    const category =
      card.dataset.category;

    showLocations(category);

  });

});


/* =====================================
   SHOW LOCATIONS
===================================== */

function showLocations(category) {

  const data =
    natureData[category];

  if (!data) return;


  categoryView.classList.add("hidden");

  locationView.classList.remove("hidden");


  locationTitle.textContent =
    data.title;

  locationEyebrow.textContent =
    data.eyebrow;

  locationDescription.textContent =
    data.description;


  locationGrid.innerHTML = "";


  data.places.forEach(place => {

    const card =
      document.createElement("article");

    card.className =
      "location-card";


    card.innerHTML = `

      <div class="location-card-image">

        <img
          src="${place.image}"
          alt="${place.name}"
          loading="lazy"
        >

      </div>

      <div class="location-info">

        <h3>
          ${place.name}
        </h3>

        <a
          href="${place.map}"
          target="_blank"
          rel="noopener noreferrer"
          class="location-link"
        >
          📍 ${place.location} ↗
        </a>

        <p>
          ${place.description}
        </p>

      </div>

    `;


    locationGrid.appendChild(card);

  });


  window.scrollTo({
    top:
      locationView.offsetTop - 100,

    behavior: "smooth"
  });

}


/* =====================================
   BACK BUTTON
===================================== */

backButton.addEventListener("click", () => {

  locationView.classList.add("hidden");

  categoryView.classList.remove("hidden");


  document
    .getElementById("explore")
    .scrollIntoView({
      behavior: "smooth"
    });

});


